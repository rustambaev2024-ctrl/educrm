"""
Единственное место, где записаны определения показателей платформы.

Зачем этот файл. Аудит 9 августа 2026 показал: «активных учеников» считали
тремя разными способами, «должников» — тремя, посещаемость — с двумя разными
знаменателями. Ни одно число не было помечено как «посчитано по другому
правилу», поэтому директор видел расхождение и читал его как ошибку в данных.
Причина у всех случаев одна: правило было записано в двух-трёх местах и со
временем разошлось.

Правило теперь такое: если определение понадобилось во втором файле — оно
импортируется отсюда, а не переписывается.

Фронтовое зеркало — src/lib/data/definitions.ts. Расхождение между сторонами
ловит tests/test_definitions_parity.py: изменить одну сторону и не изменить
другую нельзя, тест упадёт.
"""

# ─────────────────────────── Посещаемость ───────────────────────────

# Отметки, которые считаются присутствием.
#
# "online" отсюда убран: такого статуса нет в Attendance.STATUS_CHOICES
# (present / absent / late / excused), он попал в список по ошибке и был
# доказательством того, что набор статусов живёт в двух местах.
ATTENDANCE_PRESENT_STATUSES = ("present", "late")

# Отметки, которые попадают в знаменатель посещаемости.
#
# "excused" (уважительный пропуск) исключён сознательно: посещаемость мерит
# дисциплину, а не болезни. Если уважительные считать пропусками, то чем
# аккуратнее администратор оформляет справки, тем хуже выглядит центр в
# отчёте — метрика начинает наказывать за хорошую работу.
ATTENDANCE_COUNTED_STATUSES = ("present", "late", "absent")


def attendance_rate_parts(queryset) -> tuple[int, int]:
    """Возвращает (присутствовал, всего учтено) по общему правилу."""
    return (
        queryset.filter(status__in=ATTENDANCE_PRESENT_STATUSES).count(),
        queryset.filter(status__in=ATTENDANCE_COUNTED_STATUSES).count(),
    )


# ──────────────────────────── Ученики ────────────────────────────

# «Учится сейчас». Замороженные не входят: заморозка ровно и означает паузу
# в занятиях, и включать её в «активных» — значит отвечать не на тот вопрос,
# который задал директор, глядя на карточку.
ACTIVE_STUDENT_STATUSES = ("active", "debtor")

# «Числится в центре, не выбыл». Шире предыдущего на "frozen". Нужно там, где
# вопрос не «сколько учится сегодня», а «сколько мы удержали»: заморозка — не
# уход, и в воронке удержания её нельзя терять.
#
# Два набора вместо одного — не дубликат: разница между ними теперь названа,
# и по названию видно, какой из них уместен.
ENROLLED_STUDENT_STATUSES = ("active", "debtor", "frozen")

# Статусы, которые исключают ученика из обоих наборов выше.
INACTIVE_STUDENT_STATUSES = ("archived", "graduate", "expelled")


def is_debtor_balance(balance) -> bool:
    """
    Должник определяется ТОЛЬКО по балансу.

    Статус "debtor" — производная величина: его выставляет
    finance.services._status_changed_for_combined_balance при каждой операции. Он умеет
    расходиться с балансом (для починки существуют tasks.py:repair-задача и
    разовый скрипт fix_debtor_statuses.py — они написаны именно потому, что
    дрейф случается). Пока статус участвует в вычислениях, он остаётся вторым
    источником правды. Считаем по балансу, статус оставляем только как метку
    в интерфейсе.
    """
    return balance is not None and balance < 0


# ──────────────────────────── Деньги ────────────────────────────

# Поступления в кассу. "manual_top_up" — то же экономическое событие, что и
# "top_up", просто внесённое сотрудником руками (оплата принята оффлайн).
INCOME_PAYMENT_TYPES = ("top_up", "manual_top_up")

# Списания с кошелька: оплата занятий и ручные списания.
CHARGE_PAYMENT_TYPES = ("charge", "manual_charge")

# Отмена поступления. reverse_payment для "top_up" и "manual_top_up" создаёт
# именно "manual_charge", поэтому из выручки его надо вычитать: иначе
# ошибочное пополнение и его исправление в сумме дают не ноль, а двойную
# выручку, и завышение остаётся в отчёте навсегда.
#
# Обратная сторона решения: ручное списание, сделанное не как отмена
# (например, «долг за учебник»), тоже уменьшит выручку. Это осознанный выбор:
# несимметричная пара операций врёт хуже и незаметнее.
INCOME_REVERSAL_TYPES = ("manual_charge",)

# ───────────────────── Как операция двигает кошелёк ─────────────────────

# Пополняют кошелёк ученика.
WALLET_CREDIT_TYPES = ("top_up", "manual_top_up", "discount", "refund")

# Уменьшают кошелёк ученика.
WALLET_DEBIT_TYPES = ("charge", "manual_charge")

# Не касаются кошелька вовсе: расход организации (аренда, зарплата) идёт
# мимо ученика.
NON_WALLET_TYPES = ("expense",)


def wallet_delta(payment_type: str, amount):
    """
    На сколько операция двигает баланс кошелька: со знаком.

    Единственное место, где записано это правило. Оно нужно в двух разных
    местах — при проведении платежа и при сверке балансов с историей — и
    раньше было переписано в обоих. Разойдись они, сверка «чинила» бы
    правильные балансы на неправильные, и заметить это было бы нечем.
    """
    if payment_type in WALLET_DEBIT_TYPES:
        return -amount
    if payment_type in WALLET_CREDIT_TYPES:
        return amount
    return type(amount)(0)


from django.db.models import F, QuerySet


def with_combined_balance(queryset: QuerySet) -> QuerySet:
    """Аннотирует queryset учеников полем combined_balance =
    wallet_balance + bonus_balance. Использовать вместо прямой
    фильтрации по wallet_balance везде, где решается вопрос "должник или
    нет" — единая точка того, что складывается; при следующем изменении
    (например, появится третий вид баланса) правится один раз, а не в
    девяти местах по всему бэкенду."""
    return queryset.annotate(combined_balance=F("wallet_balance") + F("bonus_balance"))
